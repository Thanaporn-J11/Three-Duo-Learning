  final String subtitle;
  final String imagePath;
  final IconData icon;
  final Color color;
  final List<GuessWord> words;

  /// Words that look too alike in a picture (e.g. Lemon / Lime). They are
  /// never offered together as answer choices.
  final List<List<String>> lookAlikes;

  const GuessCategory({
    required this.id,
    required this.title,
    required this.subtitle,
    required this.imagePath,
    required this.icon,
    required this.color,
    required this.words,
    this.lookAlikes = const [],
  });
}

