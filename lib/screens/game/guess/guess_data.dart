import 'package:flutter/material.dart';

// Words and pictures of the "ทายภาพ" game.
// The server keeps the same word list (threeduo_backend/utils/guessCatalog.js)
// to check answers before giving coins: change both together.

class GuessWord {
  /// English word shown on the button and read aloud. Also the answer the
  /// server checks, so keep it exactly as in guessCatalog.js.
  final String word;
  final String thai;
  final String imagePath;

  const GuessWord(this.word, this.thai, this.imagePath);
}

class GuessCategory {
  /// Stable id used for saved progress and by the server (e.g. 'animal').
  final String id;
